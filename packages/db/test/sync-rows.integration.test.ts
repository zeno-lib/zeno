import { asc, eq, inArray, sql, TransactionRollbackError } from "drizzle-orm"
import {
  bigint,
  integer,
  type PgAsyncDatabase,
  text,
} from "drizzle-orm/pg-core"
import type { PostgresJsQueryResultHKT } from "drizzle-orm/postgres-js"
import { afterAll, describe, expect, it } from "vitest"
import { createAdminClient } from "../src/index"
import { syncRows } from "../src/query"
import { primaryId, unsecureTable } from "../src/schema"

// Connects for real (SUPABASE_DATABASE_URL from .env.test), so start the local
// stack with `pnpm dev` first. Every test creates its tables inside a
// transaction that rolls back, so nothing reaches the shared database.

// Synced by its surrogate `id`.
const lines = unsecureTable("lines", {
  id: primaryId("sequential"),
  note: text(),
  orderId: bigint({ mode: "number" }).notNull(),
  product: text().notNull(),
  quantity: integer().notNull().default(1),
})

// Synced by a natural key with nullable parts, and no `id` at all.
const members = unsecureTable("members", {
  groupId: text(),
  personId: text(),
  role: text().notNull().default("member"),
  teamId: bigint({ mode: "number" }).notNull(),
})

// Ids the caller assigns: the column has no default.
const codes = unsecureTable("codes", {
  id: primaryId("assigned"),
  label: text().notNull(),
  listId: bigint({ mode: "number" }).notNull(),
})

// The plain `unique` treats nulls as distinct, so it never stops a duplicate
// `(team, person, null)`: only syncRows' own matching does.
const tables = [
  sql`create temp table lines (
    id bigint generated by default as identity primary key,
    order_id bigint not null,
    product text not null,
    quantity integer not null default 1,
    note text,
    unique (order_id, product)
  )`,
  sql`create temp table members (
    team_id bigint not null,
    person_id text,
    group_id text,
    role text not null default 'member',
    unique (team_id, person_id, group_id)
  )`,
  sql`create temp table codes (
    id varchar primary key,
    list_id bigint not null,
    label text not null
  )`,
]

const db = createAdminClient()

afterAll(async () => {
  await db.close()
})

type Db = PgAsyncDatabase<PostgresJsQueryResultHKT>

// Runs `run` against fresh tables in a transaction that always rolls back.
const withTables = (run: (tx: Db) => Promise<void>) =>
  db
    .transaction(async (tx) => {
      for (const statement of tables) {
        // biome-ignore lint/performance/noAwaitInLoops: one connection, one statement at a time
        await tx.execute(statement)
      }
      await run(tx)
      tx.rollback()
    })
    .catch((error: unknown) => {
      if (!(error instanceof TransactionRollbackError)) {
        throw error
      }
    })

const linesOf = (tx: Db, orderId: number) =>
  tx
    .select()
    .from(lines)
    .where(eq(lines.orderId, orderId))
    .orderBy(asc(lines.id))

// Three lines on order 1, and one on order 2 that no test may touch.
const seedLines = async (tx: Db) => {
  const [apple, pear, plum, other] = await tx
    .insert(lines)
    .values([
      { orderId: 1, product: "apple" },
      { note: "gift wrap", orderId: 1, product: "pear" },
      { orderId: 1, product: "plum" },
      { orderId: 2, product: "apple" },
    ])
    .returning()
  if (!(apple && pear && plum && other)) {
    throw new Error("Seeding the lines failed")
  }
  return { apple, other, pear, plum }
}

describe("syncRows by id", () => {
  it("updates the rows it keeps, inserts new ones and deletes the rest, in input order", () =>
    withTables(async (tx) => {
      const { apple, other, pear } = await seedLines(tx)

      const saved = await syncRows(tx, lines, {
        parent: { orderId: 1 },
        rows: [
          { product: "fig" },
          { id: pear.id, product: "pear", quantity: 3 },
          { id: apple.id, product: "green apple" },
        ],
      })

      expect(saved.map(({ id, product }) => [id, product])).toEqual([
        [expect.any(Number), "fig"],
        [pear.id, "pear"],
        [apple.id, "green apple"],
      ])
      expect(saved[1]?.quantity).toBe(3)
      expect(await linesOf(tx, 1)).toEqual(
        [...saved].sort((a, b) => a.id - b.id)
      )
      expect(await linesOf(tx, 2)).toEqual([other])
    }))

  it("leaves a column the row doesn't carry as it was", () =>
    withTables(async (tx) => {
      const { pear } = await seedLines(tx)

      const [saved] = await syncRows(tx, lines, {
        parent: { orderId: 1 },
        rows: [{ id: pear.id, note: undefined, product: "pear", quantity: 2 }],
      })

      expect(saved).toMatchObject({ note: "gift wrap", quantity: 2 })
    }))

  it("doesn't write a kept row whose values haven't changed", () =>
    withTables(async (tx) => {
      const { apple, pear } = await seedLines(tx)
      // An update writes a new row version, which moves the row's ctid.
      const ctids = () =>
        tx.execute<{ ctid: string }>(
          sql`select ctid::text from lines where order_id = 1 order by id`
        )
      const before = await ctids()

      await syncRows(tx, lines, {
        parent: { orderId: 1 },
        rows: [
          { id: apple.id, product: "apple", quantity: 2 },
          { id: pear.id, note: "gift wrap", product: "pear", quantity: 1 },
        ],
      })

      const after = await ctids()
      expect(after[0]?.ctid).not.toBe(before[0]?.ctid)
      expect(after[1]?.ctid).toBe(before[1]?.ctid)
    }))

  it("keeps a new row's id when the id column has no default", () =>
    withTables(async (tx) => {
      const [saved] = await syncRows(tx, codes, {
        parent: { listId: 1 },
        rows: [{ id: "net-30", label: "Net 30" }],
      })

      expect(saved).toEqual({ id: "net-30", label: "Net 30", listId: 1 })
    }))

  it("inserts a row whose id belongs to another parent, leaving that row alone", () =>
    withTables(async (tx) => {
      const { other } = await seedLines(tx)

      const [saved] = await syncRows(tx, lines, {
        parent: { orderId: 1 },
        rows: [{ id: other.id, product: "apple", quantity: 9 }],
      })

      expect(saved?.id).not.toBe(other.id)
      expect(saved).toMatchObject({ orderId: 1, quantity: 9 })
      expect(await linesOf(tx, 2)).toEqual([other])
    }))

  it("deletes a removed row before inserting one with the same unique key", () =>
    withTables(async (tx) => {
      const { apple } = await seedLines(tx)

      const saved = await syncRows(tx, lines, {
        parent: { orderId: 1 },
        rows: [{ product: "apple", quantity: 2 }],
      })

      expect(saved).toHaveLength(1)
      expect(saved[0]?.id).not.toBe(apple.id)
      expect(await linesOf(tx, 1)).toEqual(saved)
    }))

  it("removes every row of the parent for an empty list", () =>
    withTables(async (tx) => {
      const { other } = await seedLines(tx)

      expect(
        await syncRows(tx, lines, { parent: { orderId: 1 }, rows: [] })
      ).toEqual([])
      expect(await linesOf(tx, 1)).toEqual([])
      expect(await linesOf(tx, 2)).toEqual([other])
    }))

  it("hands the removed rows to remove instead of deleting them", () =>
    withTables(async (tx) => {
      const { apple, pear, plum } = await seedLines(tx)
      const removed: unknown[] = []

      await syncRows(tx, lines, {
        parent: { orderId: 1 },
        remove: (inner, rows) => {
          removed.push(...rows)
          return inner
            .update(lines)
            .set({ note: "archived" })
            .where(
              inArray(
                lines.id,
                rows.map(({ id }) => id)
              )
            )
        },
        rows: [{ id: apple.id, product: "apple" }],
      })

      expect(removed).toEqual([pear, plum])
      expect(
        (await linesOf(tx, 1)).map(({ note, product }) => [product, note])
      ).toEqual([
        ["apple", null],
        ["pear", "archived"],
        ["plum", "archived"],
      ])
    }))

  it("rejects two rows with the same id and writes nothing", () =>
    withTables(async (tx) => {
      const { apple } = await seedLines(tx)
      const before = await linesOf(tx, 1)

      await expect(
        syncRows(tx, lines, {
          parent: { orderId: 1 },
          rows: [
            { id: apple.id, product: "apple" },
            { product: "fig" },
            { id: apple.id, product: "red apple" },
          ],
        })
      ).rejects.toThrow("Rows 0 and 2 have the same key")
      expect(await linesOf(tx, 1)).toEqual(before)
    }))

  it("undoes its own writes when a statement fails, leaving the caller's transaction usable", () =>
    withTables(async (tx) => {
      await seedLines(tx)
      const before = await linesOf(tx, 1)

      await expect(
        syncRows(tx, lines, {
          parent: { orderId: 1 },
          rows: [{ product: null as unknown as string }],
        })
      ).rejects.toThrow()
      expect(await linesOf(tx, 1)).toEqual(before)
    }))

  it("refuses a parent without a value, which would sync the whole table", () =>
    withTables(async (tx) => {
      await expect(
        syncRows(tx, lines, { parent: { orderId: undefined }, rows: [] })
      ).rejects.toThrow("syncRows needs a value for every parent column")
    }))

  it("refuses a parent of nulls alone, which would sync every orphaned row", () =>
    withTables(async (tx) => {
      await expect(
        syncRows(tx, lines, {
          parent: { orderId: null as unknown as number },
          rows: [],
        })
      ).rejects.toThrow("syncRows needs a parent column that isn't null")
    }))
})

describe("syncRows by key", () => {
  const membersOf = (tx: Db, teamId: number) =>
    tx
      .select()
      .from(members)
      .where(eq(members.teamId, teamId))
      .orderBy(asc(members.personId), asc(members.groupId))

  const seedMembers = (tx: Db) =>
    tx
      .insert(members)
      .values([
        { groupId: null, personId: "ada", teamId: 1 },
        { groupId: "ops", personId: null, teamId: 1 },
        { groupId: null, personId: "bob", teamId: 1 },
        { groupId: null, personId: "ada", teamId: 2 },
      ])
      .returning()

  it("matches null key parts, updates and keeps what's listed, inserts and deletes the rest", () =>
    withTables(async (tx) => {
      const [, ops, , otherTeam] = await seedMembers(tx)

      const saved = await syncRows(tx, members, {
        key: ["personId", "groupId"],
        parent: { teamId: 1 },
        rows: [
          { groupId: null, personId: "ada", role: "owner" },
          { groupId: "ops", personId: null },
          { groupId: "dev", personId: null },
        ],
      })

      expect(saved).toEqual([
        { groupId: null, personId: "ada", role: "owner", teamId: 1 },
        ops,
        { groupId: "dev", personId: null, role: "member", teamId: 1 },
      ])
      expect(await membersOf(tx, 1)).toHaveLength(3)
      expect(await membersOf(tx, 2)).toEqual([otherTeam])
    }))

  it("rejects two rows with the same key, nulls included", () =>
    withTables(async (tx) => {
      await expect(
        syncRows(tx, members, {
          key: ["personId", "groupId"],
          parent: { teamId: 1 },
          rows: [
            { groupId: null, personId: "ada" },
            { groupId: null, personId: "ada", role: "owner" },
          ],
        })
      ).rejects.toThrow("Rows 0 and 1 have the same key")
    }))

  it("rejects a row without a key part, which the insert would store as the default", () =>
    withTables(async (tx) => {
      await expect(
        syncRows(tx, members, {
          key: ["personId", "groupId"],
          parent: { teamId: 1 },
          rows: [{ personId: "ada" } as { groupId: null; personId: string }],
        })
      ).rejects.toThrow('Row 0 has no value for key column "groupId"')
    }))
})
