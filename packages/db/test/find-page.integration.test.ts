import { defineRelations, sql, TransactionRollbackError } from "drizzle-orm"
import { bigint, integer, text } from "drizzle-orm/pg-core"
import { afterAll, expect, it } from "vitest"
import { createAdminClient } from "../src/index"
import { findPage } from "../src/query"
import { primaryId, unsecureTable } from "../src/schema"

// Connects for real (SUPABASE_DATABASE_URL from .env.test), so start the local
// stack with `pnpm dev` first. Every test creates its tables inside a
// transaction that rolls back, so nothing reaches the shared database.

const authors = unsecureTable("authors", {
  id: primaryId("sequential"),
  name: text().notNull(),
})

const posts = unsecureTable("posts", {
  authorId: bigint({ mode: "number" }).notNull(),
  id: primaryId("sequential"),
  rank: integer().notNull(),
  title: text().notNull(),
})

const relations = defineRelations({ authors, posts }, (r) => ({
  posts: {
    author: r.one.authors({ from: r.posts.authorId, to: r.authors.id }),
  },
}))

const db = createAdminClient({ relations })

afterAll(async () => {
  await db.close()
})

type Tx = Parameters<Parameters<typeof db.transaction>[0]>[0]

// Two authors and five posts, ranks 3, 2, 2, 1, 1, so the order needs `id` to
// break the ties.
const withPosts = (run: (tx: Tx) => Promise<void>) =>
  db
    .transaction(async (tx) => {
      await tx.execute(sql`create temp table authors (
        id bigint generated by default as identity primary key,
        name text not null
      )`)
      await tx.execute(sql`create temp table posts (
        id bigint generated by default as identity primary key,
        author_id bigint not null references authors,
        rank integer not null,
        title text not null
      )`)
      await tx.insert(authors).values([{ name: "Ada" }, { name: "Linus" }])
      await tx.insert(posts).values(
        [3, 2, 2, 1, 1].map((rank, index) => ({
          authorId: (index % 2) + 1,
          rank,
          title: `Post ${index + 1}`,
        }))
      )
      await run(tx)
      tx.rollback()
    })
    .catch((error: unknown) => {
      if (!(error instanceof TransactionRollbackError)) {
        throw error
      }
    })

// `rows` reads in reverse and with a relation: the page still comes back in
// `orderBy` order, and the total counts every match, not only the page.
const readPage = (tx: Tx, offset: number, minRank = 1) =>
  findPage(
    tx.query.posts,
    { limit: 2, offset },
    {
      orderBy: (post, { asc, desc }) => [desc(post.rank), asc(post.id)],
      rows: (ids) =>
        tx.query.posts.findMany({
          columns: { id: true, title: true },
          orderBy: { id: "desc" },
          where: { id: { in: ids } },
          with: { author: { columns: { name: true } } },
        }),
      where: { rank: { gte: minRank } },
    }
  )

it("pages the matching rows in order, with their relations and the total", async () => {
  await withPosts(async (tx) => {
    await expect(readPage(tx, 0)).resolves.toEqual({
      hasMore: true,
      items: [
        { author: { name: "Ada" }, id: 1, title: "Post 1" },
        { author: { name: "Linus" }, id: 2, title: "Post 2" },
      ],
      total: 5,
    })
    await expect(readPage(tx, 2)).resolves.toMatchObject({
      hasMore: true,
      items: [{ id: 3 }, { id: 4 }],
    })
    await expect(readPage(tx, 4)).resolves.toMatchObject({
      hasMore: false,
      items: [{ id: 5 }],
      total: 5,
    })
  })
})

it("knows the total is 0 when nothing matches, and not past the last row", async () => {
  await withPosts(async (tx) => {
    await expect(readPage(tx, 0, 4)).resolves.toEqual({
      hasMore: false,
      items: [],
      total: 0,
    })
    await expect(readPage(tx, 6)).resolves.toEqual({
      hasMore: false,
      items: [],
      total: null,
    })
  })
})
